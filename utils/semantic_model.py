"""Load the semantic model YAML and render it as an LLM prompt."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from utils import app_db

DEFAULT_PATH = Path(__file__).resolve().parent.parent / "knowledge_base" / "metadata_sql.yaml"


def load_semantic_model(path: str | Path = DEFAULT_PATH, include_approved: bool = True) -> dict[str, Any]:
    """Load the YAML. Queries a human approved from user feedback (SQLite) are appended to
    ``verified_queries`` so the agent prompt learns from them without rewriting the YAML."""
    with open(path, encoding="utf-8") as f:
        model = yaml.safe_load(f)
    if include_approved:
        have = {q.get("question") for q in model.get("verified_queries", [])}
        extra = [
            {"name": q["question"], "question": q["question"], "sql": q["sql"], "verified_by": "feedback review"}
            for q in app_db.list_verified()
            if q["question"] not in have
        ]
        model["verified_queries"] = [*model.get("verified_queries", []), *extra]
    return model


def allowed_tables(model: dict[str, Any]) -> set[str]:
    return {t["name"].upper() for t in model["tables"]}


def pii_columns(model: dict[str, Any]) -> dict[str, set[str]]:
    """Map TABLE -> upper-cased names of columns tagged ``pii: true`` in the YAML."""
    out: dict[str, set[str]] = {}
    for t in model["tables"]:
        cols = {
            c["name"].upper()
            for kind in ("dimensions", "time_dimensions", "facts")
            for c in t.get(kind, [])
            if c.get("pii")
        }
        if cols:
            out[t["name"].upper()] = cols
    return out


def render_schema_prompt(model: dict[str, Any]) -> str:
    lines: list[str] = ["# Database schema (Snowflake)"]
    for t in model["tables"]:
        bt = t["base_table"]
        fq = f'{bt["database"]}.{bt["schema"]}.{bt["table"]}'
        pk = ", ".join(t.get("primary_key", {}).get("columns", []))
        lines += ["", f"## {fq}", t["description"], f"Primary key: {pk}", "Columns:"]
        for kind in ("dimensions", "time_dimensions", "facts"):
            for c in t.get(kind, []):
                if c.get("pii"):
                    # No sample values: real personal data must not reach the LLM prompt.
                    lines.append(f'- {c["name"]} ({c["data_type"]}, {kind[:-1]}) PII: never select; COUNT/filter/join only')
                    continue
                samples = ", ".join(str(v) for v in c.get("sample_values", [])[:3])
                lines.append(f'- {c["name"]} ({c["data_type"]}, {kind[:-1]}) e.g. {samples}')

    lines += ["", "# Joins (all many_to_one)"]
    for r in model.get("relationships", []):
        cond = " AND ".join(
            f'{r["left_table"]}.{c["left_column"]} = {r["right_table"]}.{c["right_column"]}'
            for c in r["relationship_columns"]
        )
        lines.append(f'- {r["left_table"]} -> {r["right_table"]}: {cond}')

    lines += ["", "# Verified example queries"]
    for q in model.get("verified_queries", []):
        sql = q["sql"].split("/* Generated by")[0].strip()
        lines += ["", f'Question: {q["question"]}', "```sql", sql, "```"]
    return "\n".join(lines)
